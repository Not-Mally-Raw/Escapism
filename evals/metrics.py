"""
Evaluation Metrics for AI Revenue Recovery System.
Enforces the strict terminal financial success state definition for NRR.

Architecture note: Production execution outcomes (ProductionOutcome) are
physically separated from ground-truth evaluation labels (GroundTruthLabel).
The join is performed only in the evaluation harness, never in production code.
This prevents label leakage by construction.
"""
from decimal import Decimal
from typing import List, Optional
from enum import StrEnum
from pydantic import BaseModel, ConfigDict, Field


class PaymentState(StrEnum):
    INTERVENTION_SENT = "INTERVENTION_SENT"
    LINK_OPENED = "LINK_OPENED"
    PAYMENT_INITIATED = "PAYMENT_INITIATED"
    AUTHORIZED = "AUTHORIZED"
    CAPTURED = "CAPTURED"
    SETTLED = "SETTLED"
    FAILED = "FAILED"


class ProductionOutcome(BaseModel):
    """
    Observable execution outcome from the production pipeline.
    Contains NO ground-truth labels — only what the system actually observed.
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    case_id: str
    amount_inr: Decimal
    final_state: PaymentState
    escalated_to_human: bool


class GroundTruthLabel(BaseModel):
    """
    Hidden evaluation label, generated by the synthetic data pipeline only.
    Never imported by production code (guardrails, decision, execution).
    Joined to ProductionOutcome by case_id in the evaluation harness only.
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    case_id: str
    ground_truth_recoverable: bool


# --- NRR Denominator Definition ---
# Eligible cases: all cases where the system attempted a recovery action.
# Legal-hold cases (routed to ESCALATE_HUMAN by regulation, not by model choice)
# should be EXCLUDED from the denominator because they were never eligible for
# automated recovery. Cases where the model chose ESCALATE_HUMAN or ABORT_COMPLIANT
# from a feasible set that included recovery actions ARE included.
#
# For the current evaluation (before the decision layer exists), the denominator
# is all cases in the synthetic batch — this is explicitly a simplification.

TERMINAL_SUCCESS_STATES = {PaymentState.CAPTURED, PaymentState.SETTLED}


def calculate_nrr(
    outcomes: List[ProductionOutcome],
    exclude_legal_hold_case_ids: Optional[set[str]] = None,
) -> tuple[Decimal, float]:
    """
    Calculates Net Revenue Recovered (NRR).

    STRICT COMPLIANCE: Only CAPTURED and SETTLED states count as revenue.

    Denominator: total at-risk revenue across eligible recovery cases.
    Cases excluded from denominator: legal-hold cases (code 07/AP03) where
    the only feasible action was ESCALATE_HUMAN by regulatory mandate.

    Returns: (total_recovered_inr, recovery_percentage)
    """
    exclude = exclude_legal_hold_case_ids or set()

    eligible = [o for o in outcomes if o.case_id not in exclude]

    total_eligible = sum(o.amount_inr for o in eligible)
    if total_eligible == 0:
        return Decimal("0.00"), 0.0

    recovered = sum(
        o.amount_inr for o in eligible
        if o.final_state in TERMINAL_SUCCESS_STATES
    )

    percentage = float(recovered / total_eligible)
    return recovered, percentage


def calculate_fer(
    outcomes: List[ProductionOutcome],
    labels: List[GroundTruthLabel],
) -> float:
    """
    Calculates False Escalation Rate (FER).
    FER = (Escalated AND Ground-Truth Recoverable) / Total Escalated

    Requires joining production outcomes with ground-truth labels by case_id.
    This join happens ONLY in the evaluation harness.
    """
    label_map = {l.case_id: l.ground_truth_recoverable for l in labels}

    escalated = [o for o in outcomes if o.escalated_to_human]
    if not escalated:
        return 0.0

    false_escalations = [
        o for o in escalated
        if label_map.get(o.case_id, False)
    ]
    return len(false_escalations) / len(escalated)
